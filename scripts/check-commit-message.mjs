#!/usr/bin/env node
/**
 * Validates a commit message (git commit-msg hook) or a pull request title
 * (CI) against Conventional Commits, and rejects headers written in Spanish:
 * everything committed to this repository is written in English.
 *
 * Usage:
 *   node scripts/check-commit-message.mjs --file .git/COMMIT_EDITMSG
 *   node scripts/check-commit-message.mjs --title "feat(careers): add LI electives"
 */
import { readFileSync } from "node:fs";

const TYPES = [
  "feat",
  "fix",
  "docs",
  "style",
  "refactor",
  "perf",
  "test",
  "build",
  "ci",
  "chore",
  "revert",
  "release",
];
const HEADER = new RegExp(
  `^(${TYPES.join("|")})(\\([a-z0-9][a-z0-9-]*\\))?!?: \\S.*$`,
);
const MAX_HEADER = 100;
const SPANISH_WORDS = new Set([
  "el",
  "los",
  "las",
  "del",
  "al",
  "para",
  "con",
  "sin",
  "que",
  "una",
  "unos",
  "unas",
  "por",
  "como",
  "cuando",
  "pero",
  "segun",
  "desde",
  "hasta",
  "tambien",
]);
const SPANISH_VERBS =
  /\b(agrega|agregar|saca|sacar|arregla|arreglar|corrige|corregir|actualiza|actualizar|suma|sumar|mejora|mejorar|elimina|eliminar|cambia|cambiar|quita|quitar|limpia|limpiar|implementa|implementar|ajusta|ajustar|crea|crear|borra|borrar|renombra|renombrar|mueve|mover)\b/i;

function fail(message) {
  console.error(`✖ ${message}`);
  process.exit(1);
}

const [mode, ...rest] = process.argv.slice(2);
let text = "";
if (mode === "--file") text = readFileSync(rest[0], "utf8");
else if (mode === "--title") text = rest.join(" ");
else fail("Usage: check-commit-message.mjs --file <path> | --title <text>");

const header =
  text
    .split("\n")
    .find((line) => line.trim() !== "" && !line.startsWith("#"))
    ?.trim() ?? "";

// Messages generated by git itself are accepted as they are.
if (/^(Merge|Revert|fixup!|squash!|amend!) /.test(header)) process.exit(0);

if (!HEADER.test(header)) {
  fail(
    `"${header}" does not follow Conventional Commits: <type>(<scope>): <subject>. Types: ${TYPES.join(", ")}.`,
  );
}
if (header.length > MAX_HEADER) {
  fail(
    `The header has ${header.length} characters; keep it under ${MAX_HEADER}.`,
  );
}

const words = header
  .toLowerCase()
  .normalize("NFD")
  .replace(/\p{M}/gu, "")
  .split(/[^a-z]+/);
const spanishWords = new Set(words.filter((word) => SPANISH_WORDS.has(word)));
if (spanishWords.size >= 2 || SPANISH_VERBS.test(header)) {
  fail(
    `"${header}" looks like Spanish. Commit messages and pull request titles are written in English (AGENTS.md).`,
  );
}
